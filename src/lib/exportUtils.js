export function exportDataAsJSON(data, filename = "agriheal_export.json") {
    const dataStr = "data:text/json;charset=utf-8," + encodeURIComponent(JSON.stringify(data, null, 2));
    const downloadAnchorNode = document.createElement("a");
    downloadAnchorNode.setAttribute("href", dataStr);
    downloadAnchorNode.setAttribute("download", filename);
    document.body.appendChild(downloadAnchorNode);
    downloadAnchorNode.click();
    downloadAnchorNode.remove();
}

export function generateFarmSummaryPDF(userProfile, records) {
    // We achieve a lightweight PDF by opening a temporary print window
    // This perfectly supports "Save as PDF" across modern mobile and web browsers
    const printWindow = window.open("", "_blank");
    if (!printWindow) return;

    const htmlContent = `
        <!DOCTYPE html>
        <html>
        <head>
            <title>Farm Summary - ${userProfile?.name || 'Farmer'}</title>
            <style>
                body { font-family: system-ui, -apple-system, sans-serif; color: #1e293b; line-height: 1.6; padding: 40px; }
                h1 { color: #064e3b; border-bottom: 2px solid #e2e8f0; padding-bottom: 10px; }
                .section { margin-top: 30px; }
                .section-title { font-size: 18px; font-weight: bold; color: #065f46; margin-bottom: 15px; background: #ecfdf5; padding: 10px; border-radius: 6px; }
                table { width: 100%; border-collapse: collapse; margin-top: 10px; }
                th, td { border: 1px solid #cbd5e1; padding: 12px; text-align: left; }
                th { background-color: #f1f5f9; font-weight: 600; }
                .footer { margin-top: 50px; font-size: 12px; color: #64748b; text-align: center; font-style: italic; }
            </style>
        </head>
        <body>
            <h1>AgriHeal Farm Summary</h1>
            <p><strong>Farmer Name:</strong> ${userProfile?.name || 'N/A'}</p>
            <p><strong>Location:</strong> ${userProfile?.location || 'N/A'}</p>
            <p><strong>Primary Crop:</strong> ${userProfile?.primaryCrop || 'N/A'}</p>
            <p><strong>Farm Size:</strong> ${userProfile?.farmSize || 'N/A'}</p>
            <p><strong>Date Generated:</strong> ${new Date().toLocaleDateString()}</p>
            
            <div class="section">
                <div class="section-title">Farm Documents & Results Inventory</div>
                ${records.length > 0 ? `
                <table>
                    <thead>
                        <tr>
                            <th>Document Title</th>
                            <th>Category</th>
                            <th>Uploaded Date</th>
                        </tr>
                    </thead>
                    <tbody>
                        ${records.map(r => `
                            <tr>
                                <td>${r.title}</td>
                                <td>${r.category}</td>
                                <td>${new Date(r.uploadedAt).toLocaleDateString()}</td>
                            </tr>
                        `).join('')}
                    </tbody>
                </table>
                ` : '<p>No farm records on file.</p>'}
            </div>

            <div class="footer">
                Automatically generated by AgriHeal.<br/>
                This is a structured export meant for farm management or personal backup.
            </div>
            <script>
                // Auto-print when loaded
                window.onload = () => {
                    setTimeout(() => {
                        window.print();
                    }, 500);
                }
            </script>
        </body>
        </html>
    `;

    printWindow.document.write(htmlContent);
    printWindow.document.close();
}
